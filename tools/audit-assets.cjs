// Inventory only: never delete an asset because a literal reference was not found.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const ignored = new Set(['.git', '.local-archives', 'tmp', 'dist', 'node_modules']);
const generated = new Set(['assets/manifest.json', 'docs/maintenance/asset-audit.json']);
const image = /\.(png|jpe?g|webp|gif|avif|svg)$/i;
function walk(dir) {
  return fs.readdirSync(path.join(root, dir), {withFileTypes: true}).flatMap(entry => {
    const file = path.posix.join(dir, entry.name);
    return ignored.has(entry.name) ? [] : entry.isDirectory() ? walk(file) : [file];
  });
}
const files = walk('');
const sources = files.filter(file => !generated.has(file) && /\.(js|cjs|css|html|md|py|txt|json)$/.test(file))
  .map(file => ({file, text: fs.readFileSync(path.join(root, file), 'utf8')}));
const runtime = sources.filter(({file}) => /^(js\/|css\/|previews\/|[^/]+\.html$)/.test(file));
const saved = JSON.parse(fs.readFileSync(path.join(root, 'minimajo-editor.json'), 'utf8'));
const configured = new Set(), missing = [];
function inspect(value) {
  if (!value || typeof value !== 'object') return;
  for (const [key, item] of Object.entries(value)) {
    if (['imageFile', 'detailImageFile', 'imagePath'].includes(key) && typeof item === 'string' && item.trim()) {
      const file = key === 'imagePath' ? item : 'assets/characters/' + item;
      configured.add(file);
      if (!fs.existsSync(path.join(root, file))) missing.push({source: 'minimajo-editor.json', file});
    }
    if (item && typeof item === 'object') inspect(item);
  }
}
inspect(saved.data);
// Check complete, literal asset URLs. Dynamic URLs are reported conservatively below.
for (const {file, text} of runtime) {
  const code = file.endsWith('.html') ? text.replace(/\bplaceholder\s*=\s*("[^"]*"|'[^']*')/g, '') : text;
  for (const match of code.matchAll(/assets\/[a-zA-Z0-9_./-]+\.(?:png|jpe?g|webp|gif|avif|svg)\b/g)) {
    if (!fs.existsSync(path.join(root, match[0]))) missing.push({source: file, file: match[0]});
  }
  if (file.endsWith('.css')) {
    for (const match of text.matchAll(/url\(\s*(?:"([^"]*)"|'([^']*)'|([^)]*))\s*\)/g)) {
      const value = (match[1] ?? match[2] ?? match[3]).trim();
      if (!value || /^(?:data:|https?:|#|var\()/i.test(value)) continue;
      const target = path.resolve(root, path.dirname(file), decodeURIComponent(value.split(/[?#]/)[0]));
      if (!fs.existsSync(target)) missing.push({source: file, file: value});
    }
  }
}
const media = files.filter(file => image.test(file));
const hashes = new Map();
const assets = [];
for (const file of media) {
  const bytes = fs.readFileSync(path.join(root, file));
  const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
  if (!hashes.has(sha256)) hashes.set(sha256, []);
  hashes.get(sha256).push(file);
  if (!file.startsWith('assets/')) continue;
  const prefix = path.posix.dirname(file) + '/';
  const literalReferences = sources.filter(source => source.text.includes(file)).map(source => source.file);
  const runtimeDirectoryReferences = runtime.filter(source => source.text.includes(prefix)).map(source => source.file);
  assets.push({file, bytes: bytes.length, sha256, configured: configured.has(file), literalReferences, runtimeDirectoryReferences});
}
const totals = {};
for (const file of files) {
  const section = file.includes('/') ? file.split('/')[0] : '(root)';
  const total = totals[section] ||= {files: 0, bytes: 0};
  total.files++;
  total.bytes += fs.statSync(path.join(root, file)).size;
}
const duplicates = [...hashes.entries()].filter(([, paths]) => paths.length > 1).map(([sha256, paths]) => ({sha256, paths}));
fs.mkdirSync(path.join(root, 'docs/maintenance'), {recursive: true});
fs.writeFileSync(path.join(root, 'assets/manifest.json'), JSON.stringify({
  note: 'Generated by node tools/audit-assets.cjs. Directory matches are hints, not proof of use. Approved unassigned icons are retained.', assets
}, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'docs/maintenance/asset-audit.json'), JSON.stringify({
  note: 'Exact duplicate images often intentionally preserve adopted sources. Historical JSON records retain their original paths; consult cleanup move maps. No automatic deletion.',
  totals, mediaFiles: media.length, duplicateGroups: duplicates, missing
}, null, 2) + '\n');
console.log(JSON.stringify({formalImages: assets.length, configuredImages: configured.size, mediaFiles: media.length, duplicateGroups: duplicates.length, missing}, null, 2));
if (missing.length) process.exitCode = 1;
